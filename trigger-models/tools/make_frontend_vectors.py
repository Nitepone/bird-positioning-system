#!/usr/bin/env python3
"""Writes firmware/test/test_frontend/vectors.h: what tools/frontends.py and
scipy's resample_poly give for a test signal the C test builds the same way
(integer arithmetic only), so the firmware's front end can be checked
against the specification natively.

Usage: make_frontend_vectors.py > firmware/test/test_frontend/vectors.h
"""

import sys
from pathlib import Path

import numpy as np
from scipy.signal import resample_poly

sys.path.insert(0, str(Path(__file__).resolve().parent))
from frontends import logmel_db_minmax, stft_sqrt_minmax  # noqa: E402

N48 = 48000 * 4  # 4 s at 48 kHz


def test_signal(n: int) -> np.ndarray:
    """As test_signal() in the C test: LCG noise plus square-wave bursts."""
    out = np.zeros(n, dtype=np.int16)
    state = 12345
    for i in range(n):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        noise = ((state >> 16) & 2047) - 1024
        period = 6 + (i >> 13) % 9
        tone = (3000 if (i // period) % 2 else -3000) if (i >> 14) & 1 else 0
        out[i] = noise + tone
    return out


def arr(name, v, fmt="%.7g"):
    body = ",".join(fmt % x for x in v)
    return f"static const float {name}[{len(v)}] = {{{body}}};\n"


def main():
    x = test_signal(N48).astype(np.float64) / 32768.0
    print("// Generated by trigger-models/tools/make_frontend_vectors.py; do not edit.")
    print(f"#define VEC_N48 {N48}")
    for f in (3, 2):
        y = resample_poly(x, 1, f)
        print(arr(f"dec{f}", y[:2000]))
        print(arr(f"dec{f}_mid", y[len(y) // 2 : len(y) // 2 + 200]))
    y16 = resample_poly(x, 1, 3).astype(np.float32)
    # The model window: 3 s from 0.5 s in.
    w16 = y16[8000 : 8000 + 48000]
    for mels in (16, 80):
        cfg = dict(sample_rate=16000, fft_length=1024, hop_length=256, frames=184, mel_bands=mels,
                   mel_fmin_hz=100.0, mel_fmax_hz=8000.0)
        print(arr(f"logmel{mels}", logmel_db_minmax(w16, cfg).ravel()))
    y24 = resample_poly(x, 1, 2).astype(np.float32)
    w24 = y24[12000 : 12000 + 60000]
    s = stft_sqrt_minmax(w24, dict(fft_length=512, frames=384)).ravel()
    print(f"#define STFT_SUM {s.astype(np.float64).sum():.6f}")
    print(arr("stft_sampled", s[::97]))


if __name__ == "__main__":
    main()
